function updateStaticTranslations() {
  const t = translations[state.lang];
  document.documentElement.lang = state.lang;
  document.title = t["meta.title"];
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.setAttribute("content", t["meta.description"]);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (t[key] !== undefined) {
      el.innerHTML = t[key];
    }
  });

  const svgStart = document.getElementById("svg-map-start");
  if (svgStart && t["hero.svgStart"]) svgStart.textContent = t["hero.svgStart"];
  const svgYou = document.getElementById("svg-map-you");
  if (svgYou && t["hero.svgYou"]) svgYou.textContent = t["hero.svgYou"];

  const isOpen = menuToggle.getAttribute("aria-expanded") === "true";
  menuToggle.setAttribute("aria-label", isOpen ? t["nav.close"] : t["nav.open"]);

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const isActive = btn.dataset.lang === state.lang;
    btn.classList.toggle("active", isActive);
    btn.setAttribute("aria-pressed", String(isActive));
  });
}

function setLanguage(lang, notify = false) {
  if (!translations[lang] || state.lang === lang) return;
  state.lang = lang;
  localStorage.setItem("brightpath_lang", lang);
  updateStaticTranslations();

  if (!questionPanel.classList.contains("is-hidden")) {
    renderQuestion();
  } else if (!document.getElementById("results").classList.contains("is-hidden")) {
    showResults();
  }

  if (notify) {
    showToast(translations[state.lang]["toast.langSwitched"]);
  }
}

function showView(name) {
  views.forEach((view) => view.classList.toggle("is-hidden", view.dataset.view !== name));
  navLinks.forEach((link) => {
    const active = link.dataset.nav === name || (name === "results" && link.dataset.nav === "test");
    link.classList.toggle("active", active);
    if (active) link.setAttribute("aria-current", "page");
    else link.removeAttribute("aria-current");
  });
  const t = translations[state.lang];
  menuToggle.setAttribute("aria-expanded", "false");
  menuToggle.setAttribute("aria-label", t["nav.open"]);
  siteNav.classList.remove("open");
  window.scrollTo({ top: 0, behavior: "smooth" });
}

function startTest() {
  state.currentQuestion = 0;
  state.answers.fill(null);
  state.currentCategory = null;
  instructionsPanel.classList.add("is-hidden");
  questionPanel.classList.remove("is-hidden");
  showView("test");
  renderQuestion();
}

function renderQuestion() {
  const currentQuestions = questions[state.lang];
  const question = currentQuestions[state.currentQuestion];
  const number = state.currentQuestion + 1;
  const t = translations[state.lang];

  questionTitle.textContent = question.question;
  questionTopic.textContent = question.topic;
  document.getElementById("question-count").textContent = t["test.questionCount"](number, currentQuestions.length);
  document.getElementById("progress-number").textContent = `${number} / ${currentQuestions.length}`;
  progressFill.style.width = `${(state.currentQuestion / currentQuestions.length) * 100}%`;
  progressTrack.setAttribute("aria-valuenow", String(state.currentQuestion));
  answerList.replaceChildren();

  question.options.forEach((option, index) => {
    const button = document.createElement("button");
    button.type = "button";
    button.className = "answer-option";
    button.setAttribute("aria-pressed", String(state.answers[state.currentQuestion] === index));
    const letter = document.createElement("span");
    letter.className = "answer-letter";
    letter.textContent = String.fromCharCode(65 + index);
    const text = document.createElement("span");
    text.className = "answer-text";
    text.textContent = option.text;
    const check = document.createElement("span");
    check.className = "answer-check";
    check.setAttribute("aria-hidden", "true");
    check.textContent = "✓";
    button.append(letter, text, check);
    button.addEventListener("click", () => selectAnswer(index));
    answerList.append(button);
  });

  previousButton.disabled = state.currentQuestion === 0;
  nextButton.disabled = state.answers[state.currentQuestion] === null;
  nextButton.innerHTML = state.currentQuestion === currentQuestions.length - 1
    ? t["test.seeResults"]
    : t["test.next"];
}

function selectAnswer(index) {
  state.answers[state.currentQuestion] = index;
  [...answerList.children].forEach((button, buttonIndex) => {
    button.setAttribute("aria-pressed", String(buttonIndex === index));
  });
  nextButton.disabled = false;
}

function moveQuestion(direction) {
  if (direction > 0 && state.answers[state.currentQuestion] === null) return;
  const currentQuestions = questions[state.lang];
  if (state.currentQuestion === currentQuestions.length - 1 && direction > 0) {
    showResults();
    return;
  }
  state.currentQuestion = Math.max(0, Math.min(currentQuestions.length - 1, state.currentQuestion + direction));
  renderQuestion();
  questionTitle.focus?.();
}

function getScores() {
  const currentCategories = categories[state.lang];
  const currentQuestions = questions[state.lang];
  const scores = Object.fromEntries(Object.keys(currentCategories).map((key) => [key, 0]));
  state.answers.forEach((answerIndex, questionIndex) => {
    if (answerIndex === null) return;
    const selected = currentQuestions[questionIndex].options[answerIndex];
    scores[selected.category] += selected.score || 1;
  });
  return scores;
}

function showResults() {
  if (state.answers.some((answer) => answer === null)) return;
  const currentCategories = categories[state.lang];
  const currentQuestions = questions[state.lang];
  const scores = getScores();
  const ranked = Object.entries(scores).sort((a, b) => b[1] - a[1]);
  state.currentCategory = ranked[0][0];
  const primary = currentCategories[state.currentCategory];
  document.getElementById("result-heading").textContent = primary.name;
  document.getElementById("result-description").textContent = primary.description;
  const answerInsights = state.answers
    .map((answerIndex, questionIndex) => currentQuestions[questionIndex].options[answerIndex])
    .filter((answer) => answer.category === state.currentCategory)
    .map((answer) => answer.insight);
  renderList("strength-list", [...new Set([...answerInsights, ...primary.strengths])].slice(0, 4));
  renderTags("areas-list", primary.areas);
  renderTags("study-list", primary.studies);
  renderTags("careers-list", primary.careers);
  document.getElementById("growth-tip").textContent = primary.tip;
  renderAlternatives(ranked.slice(1).filter(([, score]) => score >= 2 && score >= scores[state.currentCategory] * 0.4).slice(0, 2));
  instructionsPanel.classList.remove("is-hidden");
  questionPanel.classList.add("is-hidden");
  showView("results");
}

function renderList(elementId, items) {
  const list = document.getElementById(elementId);
  list.replaceChildren(...items.map((item) => {
    const li = document.createElement("li");
    li.textContent = item;
    return li;
  }));
}

function renderTags(elementId, items) {
  const list = document.getElementById(elementId);
  list.replaceChildren(...items.map((item) => {
    const tag = document.createElement("span");
    tag.className = "tag";
    tag.textContent = item;
    return tag;
  }));
}

function renderAlternatives(alternatives) {
  const currentCategories = categories[state.lang];
  const section = document.getElementById("alternatives-section");
  const grid = document.getElementById("alternative-grid");
  grid.replaceChildren();
  section.classList.toggle("is-hidden", alternatives.length === 0);
  alternatives.forEach(([key]) => {
    const category = currentCategories[key];
    const card = document.createElement("article");
    card.className = "alternative-card";
    const symbol = document.createElement("span");
    symbol.className = "alternative-symbol";
    symbol.setAttribute("aria-hidden", "true");
    symbol.textContent = category.symbol;
    const copy = document.createElement("div");
    const heading = document.createElement("h3");
    heading.textContent = category.name;
    const description = document.createElement("p");
    description.textContent = category.alternative;
    copy.append(heading, description);
    card.append(symbol, copy);
    grid.append(card);
  });
}

